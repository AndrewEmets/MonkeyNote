"""Extract SMuFL glyph outlines from Bravura into js/data/glyphs.js.

Usage: python tools/extract-glyphs.py path/to/Bravura.otf
Requires: pip install fonttools
Font source: https://github.com/steinbergmedia/bravura (redist/otf/Bravura.otf), SIL OFL 1.1.

Output coordinates are in staff spaces (1 staff space = 250 font units),
y pointing down, origin at the glyph's SMuFL origin.
"""
import json
import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

GLYPHS = {
    "brace": 0xE000,
    "gClef": 0xE050,
    "cClef": 0xE05C,
    "fClef": 0xE062,
    "noteheadWhole": 0xE0A2,
    "noteheadHalf": 0xE0A3,
    "noteheadBlack": 0xE0A4,
    "accidentalFlat": 0xE260,
    "accidentalNatural": 0xE261,
    "accidentalSharp": 0xE262,
    "accidentalDoubleSharp": 0xE263,
    "accidentalDoubleFlat": 0xE264,
}
SPACE = 250.0


def fmt(v):
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def main(font_path):
    font = TTFont(font_path)
    cmap = font.getBestCmap()
    glyph_set = font.getGlyphSet()
    out = {}
    for name, cp in GLYPHS.items():
        gname = cmap[cp]
        svg = SVGPathPen(glyph_set, ntos=fmt)
        glyph_set[gname].draw(TransformPen(svg, (1 / SPACE, 0, 0, -1 / SPACE, 0, 0)))
        bounds = BoundsPen(glyph_set)
        glyph_set[gname].draw(bounds)
        x0, y0, x1, y1 = bounds.bounds
        out[name] = {
            "d": svg.getCommands(),
            "advance": round(glyph_set[gname].width / SPACE, 3),
            # bbox in staff spaces, y down: [left, top, right, bottom]
            "bbox": [round(x0 / SPACE, 3), round(-y1 / SPACE, 3), round(x1 / SPACE, 3), round(-y0 / SPACE, 3)],
        }
    target = Path(__file__).resolve().parent.parent / "js" / "data" / "glyphs.js"
    target.write_text(
        "// Generated by tools/extract-glyphs.py from Bravura (SIL OFL 1.1). Do not edit.\n"
        "export const GLYPHS = " + json.dumps(out, indent=1) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {target} ({len(out)} glyphs)")


if __name__ == "__main__":
    main(sys.argv[1])
