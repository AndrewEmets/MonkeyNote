// Convert MonkeyType's frontend/src/ts/constants/themes.ts into js/data/themes.js.
// Usage: node tools/build-themes.js path/to/themes.ts
// Source: https://github.com/monkeytypegame/monkeytype (GPL-3.0). Parsed as text, never executed.
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(process.argv[2], "utf8");
const body = src.slice(src.indexOf("export const themes"));
const KEYS = ["bg", "main", "caret", "sub", "subAlt", "text", "error", "errorExtra", "colorfulError", "colorfulErrorExtra"];
const themes = {};
const block = /^\s{2}"?([\w-]+)"?:\s*\{([^}]*)\}/gm;
let m;
while ((m = block.exec(body))) {
  const [, name, inner] = m;
  const t = {};
  for (const k of KEYS) {
    const v = inner.match(new RegExp(`\\b${k}:\\s*"(#[0-9a-fA-F]{3,8})"`));
    if (!v) throw new Error(`theme ${name}: missing ${k}`);
    t[k] = v[1].toLowerCase();
  }
  themes[name] = t;
}
const names = Object.keys(themes).sort();
const lines = names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(themes[n])},`);
writeFileSync(
  new URL("../js/data/themes.js", import.meta.url),
  "// Generated by tools/build-themes.js from MonkeyType (GPL-3.0). Do not edit.\n" +
    "export const THEMES = {\n" + lines.join("\n") + "\n};\n",
);
console.log(`wrote ${names.length} themes`);
